"""Считает материал по кандидатам в курсы (названия из тем, найденных снизу вверх).
Запуск: python3 scripts/course_candidates.py   -> печатает таблицу и пишет analysis/topics/course_candidates.csv
"""
import csv, re, sqlite3
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parent.parent
CAND = {
 "01 Вернуть бывшую/бывшего":      r"верн\w*|бывш\w+|расстав\w+|разрыв\w*|колишн\w+|розстав\w+",
 "02 Баланс значимости":           r"значимост\w+|баланс\w*|сильн\w+ позици|слаб\w+ позици|значущ\w+",
 "03 Уважение и самоуважение":     r"уважен\w+|самоуваж\w+|самооценк\w+|поваг\w+|самоповаг\w+|ценност\w+|ценит\w*",
 "04 Дистанция и пауза":           r"дистанц\w+|игнор\w*|пауз\w+|отдал\w+|отстран\w+",
 "05 Типы привязанности":          r"привязанн\w+|тревожн\w+|избегающ\w+|созависим\w+|дезорганиз\w+",
 "06 Измена и прощение":           r"измен\w*|предат\w+|предал\w*|неверн\w+|зрад\w+|стосунки після зради",
 "07 Ревность":                    r"ревн\w+|ревнощ\w+",
 "08 Токсичные отношения и нарциссы": r"токсич\w+|манипул\w+|нарцисс\w+|абьюз\w*|газлайт\w*|унижен\w+|шантаж\w*",
 "09 Границы":                     r"границ\w+|кордон\w+|граници\w*",
 "10 Брак, жена, развод":          r"\bжен[аыуео]\b|\bмуж\w*|брак\w*|развод\w*|супруг\w*|семь\w+|сім'\w+",
 "11 Дети и семья после развода":  r"ребён\w+|ребен\w+|дет[ьиейям]\w*|алимент\w*|опек\w+|отц\w+",
 "12 Выбор партнёра":              r"выбр\w+|выбор\w*|пригодн\w+|непригодн\w+|подходящ\w+|критери\w+|типаж\w*|идеальн\w+",
 "13 Знакомства (улица, клуб, соцсети)": r"знакомств\w+|знайом\w+|познаком\w+|познайом\w+|улиц\w+|клуб\w*|тиндер\w*|тинд\w+|сайт\w* знаком\w+|подойти|подход\w*",
 "14 Свидания и близость":         r"свидани\w+|побачен\w+|поцел\w+|целова\w+|флирт\w*|близост\w+|соблазн\w+|зваблен\w+|секс\w*",
 "15 Переписка":                   r"переписк\w+|переписыв\w+|сообщен\w+|\bсмс\b|голосов\w+",
 "16 Остывание и выгорание":       r"остыв\w+|выгорани\w+|охлажд\w+|потеря\w* интерес\w*|скучн\w+|згасан\w+|интерес\w* пропа\w+",
 "17 Отношения на расстоянии":     r"расстоян\w+|на расстоянии|дальн\w+ отношен\w+",
 "18 Дружба и френдзона":          r"друж\w+|френдзон\w+|друг\b",
 "19 Деньги, подарки, быт в паре": r"деньг\w+|финанс\w+|подарк\w+|подарун\w+|зарплат\w+|быт\w*",
 "20 Саморазвитие и уверенность":  r"саморазвит\w+|уверенност\w+|впевненіст\w+|привычк\w+|дисциплин\w+|страх\w*|тревог\w+|прокрастин\w+",
 "21 Как влюбить и удержать интерес": r"влюбить\w*|влюбл\w+|удержать\w*|удержива\w+|заинтересова\w+|привлеч\w+|понравить\w+|нравиш\w+",
 "22 Для женщин: как строить отношения с мужчиной": r"мужчин\w+|мужик\w*|его\b|он\b|чоловік\w*",
}
rx = {k: re.compile(v, re.I) for k, v in CAND.items()}
c = sqlite3.connect(ROOT / "data" / "heal.db")
rows = c.execute("select id,channel,title,words,text from videos where status='готово'").fetchall()
stat = {k: dict(core=0, core_words=0, broad=0, broad_words=0, ch=Counter(), vids=[]) for k in CAND}
for vid, ch, title, w, text in rows:
    t = title.lower(); body = text.lower(); n = max(w, 1)
    for k, r in rx.items():
        th = len(r.findall(t)); dens = len(r.findall(body)) * 1000 / n
        s = stat[k]
        if th:
            s["core"] += 1; s["core_words"] += w; s["ch"][ch.split()[0]] += 1; s["vids"].append(vid)
        if dens >= 6 or th:
            s["broad"] += 1; s["broad_words"] += w
print(f"{'курс':52}{'в заголовке':>12}{'слов':>10}{'широко':>8}   каналы")
out = []
for k, s in stat.items():
    print(f"{k:52}{s['core']:>12}{s['core_words']:>10,}{s['broad']:>8}   " + ", ".join(f"{a} {b}" for a, b in s['ch'].most_common(4)))
    out.append([k, s["core"], s["core_words"], s["broad"], s["broad_words"], "; ".join(f"{a} {b}" for a, b in s['ch'].most_common(6))])
p = ROOT / "analysis" / "topics" / "course_candidates.csv"
with open(p, "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["курс", "видео_с_темой_в_заголовке", "слов", "видео_широко", "слов_широко", "каналы"]); w.writerows(out)
